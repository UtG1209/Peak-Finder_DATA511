"""Step 2: download elevation (Terrarium) and aerial imagery (USGS) tiles, then fill gaps.

Zoom plan (bounds come from the trail config, each [west, south, east, north]):
  Elevation  z10-12 over "wide", z13 over "mid", z14 over "core" (z14 only for the profile, not served)
  Imagery    z12 over "wide", z13-14 over "mid", z15-16 over "core"
Then every missing z13 elevation tile inside "wide" is generated by upsampling its z12 parent,
so the 3D terrain never has holes (MapLibre drops missing terrain tiles to sea level).

Saves to cache/<trail>/dem/{z}/{x}/{y}.png and cache/<trail>/img/{z}/{x}/{y}.jpg.
Usage: python pipeline/s2_fetch_tiles.py angels_landing
"""
import sys
from concurrent.futures import ThreadPoolExecutor

import numpy as np
from PIL import Image

from common import (DEM_URL, IMG_URL, cache_dir, decode_terrarium, encode_terrarium,
                    exists, http_get, load_config, save_bytes, tiles_in_bbox)


def plan(cfg):
    b = cfg["bounds"]
    dem = [t for z in (10, 11, 12) for t in tiles_in_bbox(b["wide"], z)]
    dem += tiles_in_bbox(b["mid"], 13) + tiles_in_bbox(b["core"], 14)
    img = tiles_in_bbox(b["wide"], 12)
    img += [t for z in (13, 14) for t in tiles_in_bbox(b["mid"], z)]
    img += [t for z in (15, 16) for t in tiles_in_bbox(b["core"], z)]
    return dem, img


def fetch(kind, tile, root):
    z, x, y = tile
    ext = "png" if kind == "dem" else "jpg"
    path = root / kind / str(z) / str(x) / f"{y}.{ext}"
    if exists(path):
        return "cached"
    url = (DEM_URL if kind == "dem" else IMG_URL).format(z=z, x=x, y=y)
    r = http_get(url)
    if r.status_code != 200 or len(r.content) < 200:
        return "missing"
    save_bytes(path, r.content)
    return "ok"


def fill_dem_z13(cfg, root):
    """Create z13 elevation tiles for the whole 'wide' box from z12 parents (bilinear upsample)."""
    made = 0
    for z, x, y in tiles_in_bbox(cfg["bounds"]["wide"], 13):
        p = root / "dem" / "13" / str(x) / f"{y}.png"
        if p.exists():
            continue
        parent = root / "dem" / "12" / str(x // 2) / f"{y // 2}.png"
        if not parent.exists():
            continue
        e = decode_terrarium(parent).astype(np.float32)
        big = np.asarray(Image.fromarray(e, mode="F").resize((512, 512), Image.BILINEAR))
        qx, qy = (x % 2) * 256, (y % 2) * 256
        p.parent.mkdir(parents=True, exist_ok=True)
        encode_terrarium(big[qy:qy + 256, qx:qx + 256].astype(np.float64)).save(p, optimize=True)
        made += 1
    return made


def main(trail_id):
    cfg = load_config(trail_id)
    root = cache_dir(trail_id)
    dem, img = plan(cfg)
    for kind, tiles in (("dem", dem), ("img", img)):
        with ThreadPoolExecutor(max_workers=8) as ex:
            res = list(ex.map(lambda t: fetch(kind, t, root), tiles))
        print(f"[tiles] {kind}: {len(tiles)} planned, "
              f"{res.count('ok')} downloaded, {res.count('cached')} cached, {res.count('missing')} missing")
    print(f"[tiles] generated {fill_dem_z13(cfg, root)} filler z13 elevation tiles")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "angels_landing")
